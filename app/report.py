from datetime import date
from io import BytesIO
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.graphics.shapes import Drawing, String
from reportlab.graphics.charts.lineplots import LinePlot
from reportlab.graphics.widgets.markers import makeMarker
from app.growth import weight_at_z, growth_alert
from app.models import Recommendation

TEAL = colors.HexColor("#0E7A66")
ORANGE = colors.HexColor("#F0962E")
GREY = colors.HexColor("#9A9A9A")
LIGHT = colors.HexColor("#E8F3F0")
GRID = colors.HexColor("#B7CCC7")
WHO_LINES = (("WHO 3rd", -1.881, GREY), ("WHO 50th", 0, TEAL), ("WHO 97th", 1.881, GREY))
DISCLAIMER = (
    "This report is generated by Coco NutriCare from the data entered by the parent. Growth percentiles use the "
    "WHO weight-for-age standard (0-5 years) and nutrition plans are general guidance. It is not a medical "
    "diagnosis and does not replace a doctor's assessment."
)

base = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=base["Title"], textColor=TEAL, fontSize=20, spaceAfter=2)
H2 = ParagraphStyle("h2", parent=base["Heading2"], textColor=TEAL, fontSize=13, spaceBefore=12, spaceAfter=6)
BODY = ParagraphStyle("body", parent=base["BodyText"], fontSize=10, leading=13)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8.5, leading=11, textColor=colors.HexColor("#555555"))


def info_table(rows):
    data = [[Paragraph(f"<b>{label}</b>", BODY), Paragraph(escape(str(value)), BODY)] for label, value in rows]
    table = Table(data, colWidths=[48 * mm, 126 * mm])
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, GRID),
        ("BACKGROUND", (0, 0), (0, -1), LIGHT),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return table


def data_table(header, rows, widths):
    table = Table([header] + rows, colWidths=widths, repeatRows=1)
    table.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, GRID),
        ("BACKGROUND", (0, 0), (-1, 0), TEAL),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
    ]))
    return table


def growth_chart(child, records):
    points = []
    for record in records:
        age_days = (record.date - child.date_of_birth).days
        if 0 <= age_days <= 1856:
            points.append((age_days, record.weight_kg))
    if not points:
        return None
    start = max(0, points[0][0] - 60)
    end = min(1856, points[-1][0] + 60)
    step = max(1, (end - start) // 30)
    days = list(range(start, end + 1, step))
    data = []
    for _, z, _ in WHO_LINES:
        line = []
        for day in days:
            weight = weight_at_z(child.gender, day, z)
            if weight is not None:
                line.append((day / 30.4375, weight))
        data.append(line)
    data.append([(day / 30.4375, weight) for day, weight in points])

    drawing = Drawing(174 * mm, 80 * mm)
    plot = LinePlot()
    plot.x, plot.y = 16 * mm, 14 * mm
    plot.width, plot.height = 150 * mm, 56 * mm
    plot.data = data
    for i, (_, _, colour) in enumerate(WHO_LINES):
        plot.lines[i].strokeColor = colour
        plot.lines[i].strokeWidth = 1
        plot.lines[i].strokeDashArray = (3, 2) if i != 1 else None
    plot.lines[3].strokeColor = ORANGE
    plot.lines[3].strokeWidth = 2
    plot.lines[3].symbol = makeMarker("FilledCircle")
    plot.lines[3].symbol.fillColor = ORANGE
    plot.lines[3].symbol.size = 4
    plot.xValueAxis.labelTextFormat = "%d"
    plot.yValueAxis.labelTextFormat = "%d"
    drawing.add(plot)
    drawing.add(String(90 * mm, 4 * mm, "Age (months)", fontSize=8, textAnchor="middle"))
    drawing.add(String(2 * mm, 74 * mm, "Weight (kg)", fontSize=8))
    drawing.add(String(60 * mm, 74 * mm, "Orange: child   Teal: WHO 50th   Grey dashed: WHO 3rd / 97th", fontSize=8))
    return drawing


def add_page_number(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#777777"))
    canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Coco NutriCare  |  Page {doc.page}")
    canvas.restoreState()


def build_child_report(child):
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=18 * mm,
        title=f"{child.name} - Coco NutriCare Report",
    )
    records = child.growth_records
    latest = records[-1] if records else None
    allergies = ", ".join(
        f"{a.allergen} ({a.severity}{', suspected' if a.suspected else ''})" for a in child.allergies
    ) or "None recorded"

    story = [
        Paragraph("Coco NutriCare", H1),
        Paragraph(f"Child Growth &amp; Nutrition Report &middot; Generated on {date.today().strftime('%b %d, %Y')}", SMALL),
        Spacer(1, 6),
        Paragraph("Child Profile", H2),
        info_table([
            ("Name", child.name),
            ("Date of birth", child.date_of_birth.strftime("%b %d, %Y")),
            ("Age", child.age_display),
            ("Gender", child.gender.capitalize()),
            ("Parent", f"{child.parent.name} ({child.parent.email})"),
            ("Dietary habits", child.dietary_habits or "Not set"),
            ("Allergies", allergies),
        ]),
        Paragraph("Growth Summary", H2),
    ]

    if latest:
        story.append(info_table([
            ("Last measured", latest.date.strftime("%b %d, %Y")),
            ("Weight", f"{latest.weight_kg} kg"),
            ("Height", f"{latest.height_cm} cm"),
            ("WHO weight percentile", "N/A (over 5 years)" if latest.percentile is None else latest.percentile),
            ("Trend", (latest.trend or "N/A").capitalize()),
            ("Growth alert", growth_alert(latest) or "None"),
        ]))
        chart = growth_chart(child, records)
        if chart:
            story += [Spacer(1, 6), chart]
        story.append(Paragraph("Growth History", H2))
        rows = [
            [r.date.strftime("%d %b %Y"), str(r.weight_kg), str(r.height_cm),
             "N/A" if r.percentile is None else str(r.percentile), (r.trend or "N/A").capitalize()]
            for r in reversed(records)
        ]
        story.append(data_table(["Date", "Weight (kg)", "Height (cm)", "Percentile", "Trend"], rows, [35 * mm] * 5))
    else:
        story.append(Paragraph("No growth records yet.", BODY))

    story.append(Paragraph("Latest Nutrition Plan", H2))
    rec = Recommendation.query.filter_by(child_id=child.id).order_by(Recommendation.id.desc()).first()
    plan = rec.plan if rec else None
    if plan and plan.get("breastfeeding_only"):
        story.append(Paragraph("Exclusive breastfeeding is recommended for the first 6 months (WHO).", BODY))
    elif plan:
        targets = plan.get("targets")
        if targets:
            story.append(info_table([("Daily target", (
                f"{targets['calories']} kcal, {targets['protein_g']} g protein, "
                f"{targets['iron_mg']} mg iron, {targets['calcium_mg']} mg calcium"
            ))]))
            story.append(Spacer(1, 6))
        meal_rows = [[meal, ", ".join(foods)] for meal, foods in plan["meals"].items()]
        story.append(data_table(["Meal", "Foods"], meal_rows, [35 * mm, 139 * mm]))
        story.append(Spacer(1, 6))
        review = [
            ("Allergens filtered", ", ".join(plan.get("filtered", [])) or "None"),
            ("Doctor review", rec.review_status),
        ]
        if rec.reviewer:
            review.append(("Reviewed by", f"{rec.reviewer.name} on {rec.reviewed_at.strftime('%b %d, %Y')}"))
        if rec.doctor_note:
            review.append(("Doctor's note", rec.doctor_note))
        story.append(info_table(review))
    else:
        story.append(Paragraph("No nutrition plan generated yet.", BODY))

    story += [Spacer(1, 14), Paragraph(DISCLAIMER, SMALL)]
    doc.build(story, onFirstPage=add_page_number, onLaterPages=add_page_number)
    return buffer.getvalue()